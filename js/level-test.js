/* =====================================================
   START TEST
===================================================== */

if (startTestBtn) {

    startTestBtn.addEventListener(
        "click",
        startTest
    );

}


function startTest() {

    /*
       Generate a completely new test.

       Every time the student clicks
       Start Test, the questions change.
    */

    generateTest();


    currentQuestion = 0;


    userAnswers =
        new Array(
            questions.length
        ).fill(null);


    if (introSection) {
        introSection.hidden = true;
    }


    if (resultSection) {
        resultSection.hidden = true;
    }


    if (quizSection) {
        quizSection.hidden = false;
    }


    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });


    renderQuestion();

}


/* =====================================================
   RENDER QUESTION
===================================================== */

function renderQuestion() {

    const question =
        questions[currentQuestion];


    if (!question) {
        return;
    }


    questionCounter.textContent =
        `Question ${currentQuestion + 1} of ${questions.length}`;


    questionNumber.textContent =
        String(currentQuestion + 1)
            .padStart(2, "0");


    questionText.textContent =
        question.question;


    levelBadge.textContent =
        question.level;


    const progress =
        (
            (currentQuestion + 1) /
            questions.length
        ) * 100;


    progressFill.style.width =
        `${progress}%`;


    answersContainer.innerHTML =
        "";


    question.answers.forEach(
        (answer, index) => {

            const button =
                document.createElement("button");


            button.type =
                "button";


            button.className =
                "answer-btn";


            if (
                userAnswers[currentQuestion] ===
                index
            ) {

                button.classList.add(
                    "selected"
                );

            }


            button.innerHTML = `

                <span class="answer-letter">
                    ${String.fromCharCode(65 + index)}
                </span>

                <span class="answer-text">
                    ${answer}
                </span>

            `;


            button.addEventListener(
                "click",
                () => {

                    selectAnswer(index);

                }
            );


            answersContainer.appendChild(
                button
            );

        }
    );


    previousBtn.disabled =
        currentQuestion === 0;


    if (
        currentQuestion ===
        questions.length - 1
    ) {

        nextBtn.textContent =
            "Finish Test →";

    } else {

        nextBtn.textContent =
            "Next →";

    }

}


/* =====================================================
   SELECT ANSWER
===================================================== */

function selectAnswer(index) {

    userAnswers[currentQuestion] =
        index;


    const buttons =
        answersContainer.querySelectorAll(
            ".answer-btn"
        );


    buttons.forEach(
        (button, buttonIndex) => {

            button.classList.toggle(
                "selected",
                buttonIndex === index
            );

        }
    );

}


/* =====================================================
   NEXT QUESTION
===================================================== */

if (nextBtn) {

    nextBtn.addEventListener(
        "click",
        () => {

            if (
                userAnswers[currentQuestion] === null
            ) {

                alert(
                    "Please choose an answer before continuing."
                );

                return;

            }


            if (
                currentQuestion <
                questions.length - 1
            ) {

                currentQuestion++;


                renderQuestion();


                window.scrollTo({
                    top: 0,
                    behavior: "smooth"
                });

            } else {

                showResults();

            }

        }
    );

}


/* =====================================================
   PREVIOUS QUESTION
===================================================== */

if (previousBtn) {

    previousBtn.addEventListener(
        "click",
        () => {

            if (
                currentQuestion > 0
            ) {

                currentQuestion--;


                renderQuestion();


                window.scrollTo({
                    top: 0,
                    behavior: "smooth"
                });

            }

        }
    );

}


/* =====================================================
   CALCULATE SCORE
===================================================== */

function calculateScore() {

    let score = 0;


    questions.forEach(
        (question, index) => {

            if (
                userAnswers[index] ===
                question.correct
            ) {

                score++;

            }

        }
    );


    return score;

}


/* =====================================================
   DETERMINE LEVEL
===================================================== */

function determineLevel(score) {

    /*
       LINGUA DEUTSCH CONNECT
       CONSERVATIVE PLACEMENT SYSTEM

       0–9   = A1
       10–14 = A2
       15–18 = B1
       19–20 = B2

       A student needs an extremely high
       score to be placed at B2.
    */


    if (score < 10) {

        return "A1";

    }


    if (score < 15) {

        return "A2";

    }


    if (score < 19) {

        return "B1";

    }


    return "B2";

}


/* =====================================================
   SCORE MESSAGE
===================================================== */

function getScoreMessage(score) {

    if (score < 10) {

        return "Keep building your German foundation!";

    }


    if (score < 15) {

        return "Nice work! You have a good basic German foundation.";

    }


    if (score < 19) {

        return "Great work! You demonstrate solid intermediate German skills.";

    }


    return "Excellent! You demonstrate very strong German skills.";

}


/* =====================================================
   SHOW RESULTS
===================================================== */

function showResults() {

    const score =
        calculateScore();


    const level =
        determineLevel(score);


    const data =
        resultData[level];


    if (quizSection) {

        quizSection.hidden =
            true;

    }


    if (resultSection) {

        resultSection.hidden =
            false;

    }


    resultLevel.textContent =
        level;


    resultTitle.textContent =
        data.title;


    resultDescription.textContent =
        data.description;


    recommendationText.textContent =
        data.recommendation;


    scoreValue.textContent =
        score;


    scoreMessage.textContent =
        getScoreMessage(score);


    const percentage =
        Math.round(
            (score / questions.length) * 100
        );


    /* ================================================
       SAVE RESULT
    ================================================ */

    try {

        localStorage.setItem(
            "ldcTestLevel",
            level
        );


        localStorage.setItem(
            "ldcTestScore",
            `${score}/${questions.length}`
        );


        localStorage.setItem(
            "ldcTestPercentage",
            percentage
        );

    } catch (error) {

        console.warn(
            "Could not save test result.",
            error
        );

    }


    /* ================================================
       SCORE CIRCLE
    ================================================ */

    if (scoreCircle) {

        scoreCircle.style.background =
            `conic-gradient(
                #1255d8 ${percentage}%,
                #e5e8ed ${percentage}% 100%
            )`;

    }


    /* ================================================
       REGISTRATION
    ================================================ */

    if (registerLevelBtn) {

        registerLevelBtn.href =
            "../index.html#start-learning";


        registerLevelBtn.dataset.level =
            level;

    }


    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}


/* =====================================================
   REGISTER FOR RESULT LEVEL
===================================================== */

if (registerLevelBtn) {

    registerLevelBtn.addEventListener(
        "click",
        () => {

            const level =
                registerLevelBtn.dataset.level ||
                localStorage.getItem(
                    "ldcTestLevel"
                );


            if (!level) {
                return;
            }


            /*
               Save the recommended course.

               The homepage reads this value
               and preselects the course.
            */

            try {

                localStorage.setItem(
                    "ldcRegistrationCourse",
                    level
                );

            } catch (error) {

                console.warn(
                    "Could not save registration course.",
                    error
                );

            }

        }
    );

}


