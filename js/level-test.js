/*
   Fisher-Yates shuffle.

   This gives every question a chance to appear
   in a different position each time.
*/

function shuffleArray(array) {

    const shuffled = [...array];

    for (
        let i = shuffled.length - 1;
        i > 0;
        i--
    ) {

        const j =
            Math.floor(
                Math.random() * (i + 1)
            );

        [
            shuffled[i],
            shuffled[j]
        ] = [
            shuffled[j],
            shuffled[i]
        ];

    }

    return shuffled;

}


/* =====================================================
   SHUFFLE ANSWERS
===================================================== */

function shuffleAnswers(question) {

    const answerObjects =
        question.answers.map(
            (answer, index) => ({
                text: answer,
                correct:
                    index === question.correct
            })
        );


    const shuffled =
        shuffleArray(answerObjects);


    return {
        ...question,

        answers:
            shuffled.map(
                answer => answer.text
            ),

        correct:
            shuffled.findIndex(
                answer => answer.correct
            )
    };

}


/* =====================================================
   GENERATE TEST
===================================================== */

function generateTest() {

    const levels = [
        "A1",
        "A2",
        "B1",
        "B2"
    ];


    const selectedQuestions = [];


    levels.forEach(level => {

        const levelQuestions =
            questionBank.filter(
                question =>
                    question.level === level
            );


        /*
           Randomly select 5 questions
           from each CEFR level.
        */

        const selected =
            shuffleArray(levelQuestions)
                .slice(0, 5);


        selectedQuestions.push(
            ...selected
        );

    });


    /*
       Shuffle the 20 questions so the
       levels are not always predictable.
    */

    questions =
        shuffleArray(selectedQuestions);


    /*
       Shuffle the four answer choices
       for every question.
    */

    questions =
        questions.map(
            question =>
                shuffleAnswers(question)
        );

}


